/**
 * 4. Génération des 76 appartements réalistes pour le Bloc H (Horizon)
 * Répartis sur 4 niveaux : RDC (19 apts), 1er étage (19 apts), 2ème étage (19 apts), 3ème étage (19 apts)
 */
const moroccanOwnerSurnames = [
  'Berrada', 'Tazi', 'Benjelloun', 'Alami', 'El Fassi', 'Kabbaj', 'Chraibi', 'Guessous',
  'Filali', 'Lahlou', 'Sqalli', 'Amrani', 'Idrissi', 'Bennis', 'Slaoui', 'Bensouda',
  'Mekouar', 'Sebti', 'Kadiri', 'Bouzoubaa', 'Belkahia', 'Tahiri', 'Cherkaoui', 'Mansouri',
  'Hammoudi', 'Dakhil', 'Zouiten', 'Naciri', 'Rochdi', 'El Amri', 'Hassani', 'Senoussi'
];

const firstNames = [
  'Youssef', 'Mehdi', 'Omar', 'Karim', 'Amine', 'Leila', 'Sofia', 'Fatima', 'Nadia',
  'Ghita', 'Kenzo', 'Hamza', 'Saad', 'Reda', 'Zineb', 'Salma', 'Meryem', 'Iliass',
  'Tariq', 'Sanaa', 'Hicham', 'Adil', 'Houda', 'Imane', 'Asmaa', 'Driss', 'Nabil'
];

export function generateBlockHApartments(): Apartment[] {
  const apartments: Apartment[] = [];
  const totalApartments = 76;

  for (let i = 1; i <= totalApartments; i++) {
    // Étage : 0 (RDC), 1, 2, 3
    const floor = Math.floor((i - 1) / 19);
    const doorNumber = `H-${i < 10 ? '0' + i : i}`;
    const surname = moroccanOwnerSurnames[(i * 3 + 7) % moroccanOwnerSurnames.length];
    const firstOwner = firstNames[(i * 5 + 2) % firstNames.length];
    const ownerName = `M. & Mme ${firstOwner} ${surname}`;

    // Cas spécifique demandé pour la démo : H-12
    if (i === 12) {
      apartments.push({
        id: 'apt-h-12',
        tenantId: 'tenant-pb-01',
        blockId: 'block-h',
        doorNumber: 'H-12',
        floor: 1,
        ownerName: 'M. & Mme Youssef Tazi',
        residentName: 'Youssef Tazi',
        residentType: 'owner',
        surfaceM2: 118,
        contactPhone: '+212 6 61 45 89 20',
      });
      continue;
    }

    // Ratio propriétaire / locataire ~ 70% propriétaires, 30% locataires
    const isRented = i % 3 === 0;
    const residentType = isRented ? 'tenant' : 'owner';
    const residentSurname = isRented ? moroccanOwnerSurnames[(i * 2 + 11) % moroccanOwnerSurnames.length] : surname;
    const residentFirstName = firstNames[(i * 4 + 3) % firstNames.length];
    const residentName = isRented ? `${residentFirstName} ${residentSurname}` : `${firstOwner} ${surname}`;

    apartments.push({
      id: `apt-h-${i}`,
      tenantId: 'tenant-pb-01',
      blockId: 'block-h',
      doorNumber,
      floor,
      ownerName,
      residentName,
      residentType,
      surfaceM2: 85 + (i % 5) * 15,
      contactPhone: `+212 6 ${60 + (i % 9)} ${10 + (i % 80)} ${20 + (i % 70)}`,
    });
  }

  return apartments;
}

